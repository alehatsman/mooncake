package utils

// Levenshtein returns the edit distance between a and b: the minimum
// number of single-character insertions, deletions, or substitutions
// needed to turn one into the other.
//
// Used for "did you mean" hints on unknown YAML fields (internal/config)
// and unknown nouns (internal/explain). Inputs are short identifiers, so
// the allocation-light two-row form is plenty; callers that need
// case-insensitive matching lower-case their inputs first.
func Levenshtein(a, b string) int {
	ar, br := []rune(a), []rune(b)
	if len(ar) == 0 {
		return len(br)
	}
	if len(br) == 0 {
		return len(ar)
	}
	prev := make([]int, len(br)+1)
	curr := make([]int, len(br)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(ar); i++ {
		curr[0] = i
		for j := 1; j <= len(br); j++ {
			cost := 1
			if ar[i-1] == br[j-1] {
				cost = 0
			}
			curr[j] = min3(curr[j-1]+1, prev[j]+1, prev[j-1]+cost)
		}
		prev, curr = curr, prev
	}
	return prev[len(br)]
}

func min3(a, b, c int) int {
	if b < a {
		a = b
	}
	if c < a {
		a = c
	}
	return a
}
