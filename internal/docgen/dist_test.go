// TestSplitReadme covers the small parser used by loadActionReadmes:
// front matter extraction, action: key lookup, H1 stripping, and the
// failure modes (no front matter, missing action key).
func TestSplitReadme(t *testing.T) {
	cases := []struct {
		name     string
		input    string
		wantName string
		wantBody string
	}{
		{
			name:     "full README with H1 and body",
			input:    "---\naction: file.copy\n---\n# file.copy\n\nProse here.\n",
			wantName: "file.copy",
			wantBody: "Prose here.\n",
		},
		{
			name:     "no front matter",
			input:    "# file.copy\n\nProse.\n",
			wantName: "",
			wantBody: "",
		},
		{
			name:     "front matter without action key",
			input:    "---\ntype: action\n---\n# file.copy\n",
			wantName: "",
			wantBody: "",
		},
		{
			name:     "body without H1",
			input:    "---\naction: shell\n---\nNo title here.\n",
			wantName: "shell",
			wantBody: "No title here.\n",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			name, body := splitReadme(c.input)
			if name != c.wantName {
				t.Errorf("name = %q, want %q", name, c.wantName)
			}
			if body != c.wantBody {
				t.Errorf("body = %q, want %q", body, c.wantBody)
			}
		})
	}
}

// TestLoadActionReadmes_SkipsStubs asserts the stub marker filters out
// boilerplate seed files. Builds a fake actions tree on disk so the
// test is hermetic.
func TestLoadActionReadmes_SkipsStubs(t *testing.T) {
	root := t.TempDir()

	mk := func(dir, body string) {
		if err := os.MkdirAll(filepath.Join(root, dir), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, dir, "README.md"), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	mk("copy",
		"---\naction: file.copy\n---\n"+stubMarker+"\n# file.copy\n\nstub prose\n")
	mk("shell",
		"---\naction: shell\n---\n# shell\n\nReal author-written prose.\n")
	mk("nameless",
		"---\ntype: action\n---\n# nameless\n\nbody\n") // no `action:` key → skipped

	notes, err := loadActionReadmes(root)
	if err != nil {
		t.Fatalf("loadActionReadmes: %v", err)
	}

	if _, ok := notes["file.copy"]; ok {
		t.Errorf("stub README for file.copy should have been skipped")
	}
	if got, ok := notes["shell"]; !ok {
		t.Errorf("authored README for shell missing")
	} else if !strings.Contains(got, "Real author-written prose") {
		t.Errorf("shell payload missing body content: %q", got)
	}
	if _, ok := notes["nameless"]; ok {
		t.Errorf("front-matter without action: should have been skipped")
	}
}

