// TestGenerateDist_FileTreeShape asserts the dist tree has the expected
// top-level shape and that the file list returned matches what's on
// disk. The exact action / cli counts depend on the registry — we just
// verify the *categories* are present.
func TestGenerateDist_FileTreeShape(t *testing.T) {
	gen := NewGenerator("test")
	out := t.TempDir()

	written, err := gen.GenerateDist(DistOptions{
		OutDir:  out,
		CLIRoot: &cli.App{Name: "mooncake", Commands: []*cli.Command{{Name: "apply", Usage: "u"}}},
	})
	if err != nil {
		t.Fatalf("GenerateDist: %v", err)
	}

	if len(written) == 0 {
		t.Fatalf("expected at least some files written")
	}

	// Every returned path must exist on disk.
	for _, p := range written {
		if _, err := os.Stat(p); err != nil {
			t.Errorf("returned path missing on disk: %s (%v)", p, err)
		}
	}

	// Every returned path must be sorted (callers rely on stable order
	// for drift detection + index generation).
	if !sort.StringsAreSorted(written) {
		t.Error("written paths are not sorted")
	}

	// Required top-level pages.
	for _, rel := range []string{"index.md", "llms.txt", "SUMMARY.md", "schema.md", "properties.md"} {
		if _, err := os.Stat(filepath.Join(out, rel)); err != nil {
			t.Errorf("missing required page %s: %v", rel, err)
		}
	}

	// At least one action card (registry has many).
	actions, err := os.ReadDir(filepath.Join(out, "actions"))
	if err != nil || len(actions) == 0 {
		t.Errorf("expected actions/ to be populated, got %d entries (err=%v)", len(actions), err)
	}

	// CLI dir contains the synthetic command we passed in.
	if _, err := os.Stat(filepath.Join(out, "cli", "apply.md")); err != nil {
		t.Errorf("expected cli/apply.md from synthetic CLIRoot: %v", err)
	}
}

// TestGenerateDist_Deterministic asserts two consecutive regenerations
// into separate temp dirs produce byte-identical output. This is the
// load-bearing invariant for docs-check.sh — if it ever fails, the
// drift gate becomes flaky.
func TestGenerateDist_Deterministic(t *testing.T) {
	gen1 := NewGenerator("test")
	gen2 := NewGenerator("test")
	out1, out2 := t.TempDir(), t.TempDir()

	if _, err := gen1.GenerateDist(DistOptions{OutDir: out1}); err != nil {
		t.Fatalf("regen 1: %v", err)
	}
	if _, err := gen2.GenerateDist(DistOptions{OutDir: out2}); err != nil {
		t.Fatalf("regen 2: %v", err)
	}

	// Walk one tree and compare each file against its sibling.
	err := filepath.Walk(out1, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(out1, path)
		a, errA := os.ReadFile(path)                     // #nosec G304 -- test
		b, errB := os.ReadFile(filepath.Join(out2, rel)) // #nosec G304 -- test
		if errA != nil || errB != nil {
			t.Errorf("read %s: a=%v b=%v", rel, errA, errB)
			return nil
		}
		if string(a) != string(b) {
			t.Errorf("non-deterministic output: %s differs between regens", rel)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk: %v", err)
	}
}

// TestWriteActionCards_Skeleton asserts every emitted action card has
// the YAML front matter and the standard headings that agents and
// MkDocs rely on. Sampling one card is enough — the emitter is a loop,
// not a per-action switch.
func TestWriteActionCards_Skeleton(t *testing.T) {
	gen := NewGenerator("test")
	out := t.TempDir()

	written, err := gen.writeActionCards(out)
	if err != nil {
		t.Fatalf("writeActionCards: %v", err)
	}
	if len(written) == 0 {
		t.Fatal("no action cards written")
	}

	body, err := os.ReadFile(written[0]) // #nosec G304 -- test
	if err != nil {
		t.Fatalf("read sample card: %v", err)
	}
	s := string(body)

	for _, marker := range []string{
		"---\n",               // front matter open
		"type: action\n",      // type marker for agents
		"name: ",              // action name in front matter
		"capabilities:\n",     // capabilities sub-block
		"# ",                  // H1 title
		"## Platform Support", // required heading
		"<!-- Generated by mooncake docs generate; version test -->", // deterministic footer
	} {
		if !strings.Contains(s, marker) {
			t.Errorf("action card missing marker %q in %s", marker, written[0])
		}
	}

	// Footer must not contain a timestamp pattern (that's the bug we
	// shipped a fix for; regression test).
	if strings.Contains(s, "Generated: 20") || strings.Contains(s, "Generated: 19") {
		t.Errorf("action card contains a Generated: timestamp (determinism regression):\n%s", s)
	}
}

// TestWriteCLITree_SkipsHelpAndHidden asserts the CLI walker filters
// urfave/cli's auto-generated `help` subcommand and any `Hidden: true`
// nodes. Without these filters the rendered site doubles in page count
// and exposes commands that `mooncake --help` deliberately doesn't.
func TestWriteCLITree_SkipsHelpAndHidden(t *testing.T) {
	gen := NewGenerator("test")
	out := t.TempDir()

	app := &cli.App{
		Name: "mooncake",
		Commands: []*cli.Command{
			{Name: "apply", Usage: "u"},
			{Name: "help", Usage: "auto-injected by urfave/cli"},
			{Name: "secret", Usage: "hidden", Hidden: true},
			{Name: "outer", Subcommands: []*cli.Command{
				{Name: "inner", Usage: "u"},
				{Name: "h", Usage: "auto-help alias"},
			}},
		},
	}

	if _, err := gen.writeCLITree(out, app); err != nil {
		t.Fatalf("writeCLITree: %v", err)
	}

	got := map[string]bool{}
	entries, _ := os.ReadDir(filepath.Join(out, "cli"))
	for _, e := range entries {
		got[e.Name()] = true
	}

	want := []string{"apply.md", "outer.md", "outer_inner.md"}
	for _, w := range want {
		if !got[w] {
			t.Errorf("expected cli/%s, got entries: %v", w, got)
		}
	}
	for _, skip := range []string{"help.md", "secret.md", "outer_h.md"} {
		if got[skip] {
			t.Errorf("cli/%s should have been skipped", skip)
		}
	}
}

