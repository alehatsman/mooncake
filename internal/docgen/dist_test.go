// TestWriteConceptCards_RendersReadme asserts that when a README does
// exist, its body is rendered into a stable card skeleton (front matter
// + body + footer). Builds a fake package dir on disk so the test is
// self-contained.
func TestWriteConceptCards_RendersReadme(t *testing.T) {
	root := t.TempDir()
	pkg := filepath.Join(root, "fakepkg")
	if err := os.MkdirAll(pkg, 0o755); err != nil {
		t.Fatal(err)
	}
	readme := "# fakepkg\n\nThe fake package explains a thing.\n"
	if err := os.WriteFile(filepath.Join(pkg, "README.md"), []byte(readme), 0o644); err != nil {
		t.Fatal(err)
	}

	gen := NewGenerator("test")
	out := t.TempDir()
	written, err := gen.writeConceptCards(out, []string{pkg})
	if err != nil {
		t.Fatalf("writeConceptCards: %v", err)
	}
	if len(written) != 1 {
		t.Fatalf("expected 1 concept page, got %d", len(written))
	}

	body, _ := os.ReadFile(written[0]) // #nosec G304 -- test
	s := string(body)
	for _, marker := range []string{
		"type: concept",
		"name: fakepkg",
		"The fake package explains a thing.",
		"<!-- Generated by mooncake docs generate; version test -->",
	} {
		if !strings.Contains(s, marker) {
			t.Errorf("concept card missing %q", marker)
		}
	}
}

// TestWriteIndex_GroupsBySection asserts the index/llms.txt grouping
// puts files in their expected sections based on the top-level
// subdirectory in their relative path.
func TestWriteIndex_GroupsBySection(t *testing.T) {
	gen := NewGenerator("test")
	out := t.TempDir()

	// Synthesize a written-files list spanning known sections; the
	// emitter only reads the path strings, doesn't need the files to
	// exist on disk.
	if err := os.MkdirAll(filepath.Join(out, "actions"), 0o755); err != nil {
		t.Fatal(err)
	}
	written := []string{
		filepath.Join(out, "actions", "file_copy.md"),
		filepath.Join(out, "actions", "shell.md"),
		filepath.Join(out, "cli", "apply.md"),
		filepath.Join(out, "schema.md"),
	}

	paths, err := gen.writeIndex(out, written)
	if err != nil {
		t.Fatalf("writeIndex: %v", err)
	}
	if len(paths) != 2 {
		t.Fatalf("expected index.md + llms.txt (2 paths), got %d", len(paths))
	}

	llms, _ := os.ReadFile(filepath.Join(out, "llms.txt")) // #nosec G304 -- test
	s := string(llms)

	// Section headers must appear.
	for _, h := range []string{"## Actions", "## CLI", "## Reference"} {
		if !strings.Contains(s, h) {
			t.Errorf("llms.txt missing section header %q\n---\n%s", h, s)
		}
	}
	// Action entries use dotted names (not the on-disk _ form).
	if !strings.Contains(s, "[file.copy]") {
		t.Errorf("llms.txt should display file.copy with dot, not file_copy:\n%s", s)
	}
}

