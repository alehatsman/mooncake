// TestSynthesizeStepName_Try_WithCatchAndFinally covers all three
// flags so the label tells operators what shape this try-block has
// without re-opening the YAML.
func TestSynthesizeStepName_Try_WithCatchAndFinally(t *testing.T) {
	cases := []struct {
		name string
		step config.Step
		want string
	}{
		{
			name: "try only",
			step: config.Step{Try: []config.Step{{}, {}}},
			want: "try: (2 children)",
		},
		{
			name: "try with catch",
			step: config.Step{Try: []config.Step{{}, {}}, Catch: []config.Step{{}}},
			want: "try: (2 children, +catch)",
		},
		{
			name: "try with catch + finally",
			step: config.Step{Try: []config.Step{{}}, Catch: []config.Step{{}}, Finally: []config.Step{{}}},
			want: "try: (1 children, +catch, +finally)",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := synthesizeStepName(c.step)
			if got != c.want {
				t.Errorf("synthesizeStepName = %q, want %q", got, c.want)
			}
		})
	}
}

// TestSynthesizeStepName_TruncatesLongBody catches the operator's
// "5000-step playbook generated by for $(seq 1 5000)" case from the
// proposal's receipts. Long shell commands collapse to a single
// line and truncate with `…`.
func TestSynthesizeStepName_TruncatesLongBody(t *testing.T) {
	long := strings.Repeat("a", 200)
	step := config.Step{Shell: &config.ShellAction{Cmd: long}}
	got := synthesizeStepName(step)
	if len([]rune(got)) > labelMaxLen {
		t.Errorf("synthesizeStepName length = %d, must be <= %d (got %q)", len([]rune(got)), labelMaxLen, got)
	}
	if !strings.HasSuffix(got, labelEllip) {
		t.Errorf("truncated label must end with %q; got %q", labelEllip, got)
	}
}

// TestSynthesizeStepName_EmptyStepReturnsEmpty pins backwards
// compatibility for `coverage_boost_test.go:TestGetStepDisplayName_
// NoName` — a fully empty step must NOT synthesize a misleading
// "unknown" label. The caller falls back to a blank step row.
func TestSynthesizeStepName_EmptyStepReturnsEmpty(t *testing.T) {
	got := synthesizeStepName(config.Step{})
	if got != "" {
		t.Errorf("empty step must not synthesize; got %q", got)
	}
}

// TestSynthesizeStepName_LoopStepReturnsEmpty — bare for_each /
// with_files wrappers aren't useful to label here. The loop
// children produce their own labels and the existing with_items
// path in getStepDisplayName already covers iteration display.
func TestSynthesizeStepName_LoopStepReturnsEmpty(t *testing.T) {
	step := config.Step{ForEach: &config.ForEachField{}}
	got := synthesizeStepName(step)
	if got != "" {
		t.Errorf("loop step must not synthesize; got %q", got)
	}
}

// TestSynthesizeStepName_NamedStepWinsViaGetStepDisplayName guards
// the proposal's "if user provides name:, that wins" contract by
// driving the full getStepDisplayName path.
func TestSynthesizeStepName_NamedStepWinsViaGetStepDisplayName(t *testing.T) {
	step := config.Step{
		Name:  "Install Foo",
		Shell: &config.ShellAction{Cmd: "echo hi"},
	}
	ec := &ExecutionContext{Scope: NewVariableScope()}
	got, ok := GetStepDisplayName(step, ec)
	if !ok || got != "Install Foo" {
		t.Errorf("named step must use user-supplied name; got %q (ok=%v)", got, ok)
	}
}

// TestSynthesizeStepName_UnnamedSurfacesSynthesizedViaGetStepDisplayName
// pins the integration: unnamed step → synthesizer → returned via
// the (name, true) tuple so renderers + event consumers see the
// label.
func TestSynthesizeStepName_UnnamedSurfacesSynthesizedViaGetStepDisplayName(t *testing.T) {
	step := config.Step{Shell: &config.ShellAction{Cmd: "echo hi"}}
	ec := &ExecutionContext{Scope: NewVariableScope()}
	got, ok := GetStepDisplayName(step, ec)
	if !ok {
		t.Fatalf("unnamed step must now have a synthesized display name")
	}
	if got != "shell: echo hi" {
		t.Errorf("synthesized name = %q, want %q", got, "shell: echo hi")
	}
}
