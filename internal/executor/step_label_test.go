// TestSynthesizeStepName_PerActionFormatters drives every per-action
// arm. Cases mirror the reference table in dx proposal-01 so the
// rendered shape stays in lockstep with the spec.
func TestSynthesizeStepName_PerActionFormatters(t *testing.T) {
	tmpl := "/etc/foo.conf"
	importPath := "tasks/x.yml"
	vars := map[string]interface{}{"a": 1, "b": 2, "c": 3}

	cases := []struct {
		name string
		step config.Step
		want string
	}{
		{
			name: "shell short cmd",
			step: config.Step{Shell: &config.ShellAction{Cmd: "echo hi"}},
			want: "shell: echo hi",
		},
		{
			name: "shell collapses whitespace",
			step: config.Step{Shell: &config.ShellAction{Cmd: "echo\n  hi\tthere"}},
			want: "shell: echo hi there",
		},
		{
			name: "file.write path",
			step: config.Step{FileWrite: &config.File{Path: "/tmp/x.txt"}},
			want: "file.write /tmp/x.txt",
		},
		{
			name: "file.download dest",
			step: config.Step{FileDownload: &config.Download{URL: "https://x/y", Dest: "/opt/foo"}},
			want: "file.download → /opt/foo",
		},
		{
			name: "file.copy dest",
			step: config.Step{FileCopy: &config.Copy{Src: "a", Dest: "/etc/b"}},
			want: "file.copy /etc/b",
		},
		{
			name: "file.template dest",
			step: config.Step{FileTemplate: &config.Template{Src: "s.tpl", Dest: tmpl}},
			want: "file.template /etc/foo.conf",
		},
		{
			name: "pkg single name",
			step: config.Step{Pkg: &config.Package{Name: "jq"}},
			want: "pkg jq",
		},
		{
			name: "pkg multi names",
			step: config.Step{Pkg: &config.Package{Names: []string{"jq", "yq", "curl"}}},
			want: "pkg jq (+2)",
		},
		{
			name: "log msg",
			step: config.Step{Log: &config.PrintAction{Msg: "hello"}},
			want: "log: hello",
		},
		{
			name: "http.request default GET",
			step: config.Step{HTTPRequest: &config.HTTPRequest{URL: "http://x/api"}},
			want: "http.request: GET http://x/api",
		},
		{
			name: "http.request explicit POST",
			step: config.Step{HTTPRequest: &config.HTTPRequest{Method: "POST", URL: "http://x/api"}},
			want: "http.request: POST http://x/api",
		},
		{
			name: "import path",
			step: config.Step{Import: &importPath},
			want: "import: tasks/x.yml",
		},
		{
			name: "vars count",
			step: config.Step{Vars: &vars},
			want: "vars: (3 keys)",
		},
		{
			name: "os.user name",
			step: config.Step{OsUser: &config.OsUser{Name: "deploy"}},
			want: "os.user deploy",
		},
		{
			name: "os.group name",
			step: config.Step{OsGroup: &config.OsGroup{Name: "docker"}},
			want: "os.group docker",
		},
		{
			name: "os.service name",
			step: config.Step{OsService: &config.ServiceAction{Name: "nginx"}},
			want: "os.service nginx",
		},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := synthesizeStepName(c.step)
			if got != c.want {
				t.Errorf("synthesizeStepName = %q, want %q", got, c.want)
			}
		})
	}
}

